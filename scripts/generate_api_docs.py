"""Write docs/API.md from the routes the application actually registers.

    python -m scripts.generate_api_docs

The table is generated, not hand-written, so it cannot drift from the code. Interactive
documentation with request/response schemas is also served by the running app at /docs.
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PROJECT_ROOT / "docs" / "API.md"


def main() -> int:
    # Importing the app must never touch the real database.
    with tempfile.TemporaryDirectory() as temp:
        os.environ["JOBPILOT_DATABASE_PATH"] = str(Path(temp) / "docs.db")
        from app.api.main import app

        # The OpenAPI schema lists every endpoint, including those from included routers.
        groups: dict[str, list[tuple[str, str, str]]] = {}
        for path, operations in app.openapi()["paths"].items():
            parts = [p for p in path.split("/") if p]
            group = parts[1] if len(parts) > 1 and parts[0] == "api" else "root"
            for method, operation in operations.items():
                if method.upper() not in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                    continue
                text = (operation.get("description") or operation.get("summary") or "").strip()
                summary = text.splitlines()[0] if text else ""
                groups.setdefault(group, []).append((method.upper(), path, summary))
        from app.db.database import engine

        engine.dispose()
        from app.api.main import engine as api_engine

        api_engine.dispose()

    lines = [
        "# JobPilot API reference",
        "",
        "Generated by `python -m scripts.generate_api_docs` from the routes the application registers. "
        "Run the backend and open `/docs` for request and response schemas you can try out.",
        "",
        "Authentication: none by default (local single-user mode). When `JOBPILOT_API_TOKEN` is set, every `/api` "
        "request must send `Authorization: Bearer <token>` (or `X-JobPilot-Token`); `/api/health` and the Gmail OAuth "
        "redirect stay open. See [DEPLOYMENT.md](DEPLOYMENT.md).",
        "",
    ]
    for group in sorted(groups):
        lines += [f"## {group}", "", "| Method | Path | What it does |", "|---|---|---|"]
        for method, path, summary in sorted(groups[group], key=lambda item: (item[1], item[0])):
            lines.append(f"| {method} | `{path}` | {summary.replace('|', '/')} |")
        lines.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({sum(len(v) for v in groups.values())} endpoints in {len(groups)} groups)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
